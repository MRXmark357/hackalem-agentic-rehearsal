import sys
from pathlib import Path

RULES = [
    {
        "category": "справка",
        "keywords": ["справк", "где", "как получить", "куда обрат"],
        "draft_template": "Здравствуйте! Справочную информацию и заказ документов вы можете оформить в личном кабинете или в едином деканате."
    },
    {
        "category": "жалоба",
        "keywords": ["очередь", "холодн", "пропал", "не работает", "сломал", "грязно"],
        "draft_template": "Здравствуйте! Приносим извинения за неудобства. Ваше обращение зафиксировано и передано ответственной службе для устранения проблемы."
    },
    {
        "category": "другое",
        "keywords": ["записаться", "консультаци", "встреч"],
        "draft_template": "Здравствуйте! Ваша заявка принята. Менеджер свяжется с вами для согласования точного времени."
    }
]

CUSTOM_REPLIES = {
    "Как получить справку о месте учёбы?": (
        "справка",
        "Здравствуйте! Справку об обучении можно заказать онлайн в личном кабинете студента (раздел «Услуги») либо забрать лично в деканате с 9:00 до 18:00."
    ),
    "В столовой очередь, еда холодная.": (
        "жалоба",
        "Здравствуйте! Спасибо за обратную связь. Мы передали сигнал руководству столовой и службе контроля питания для проверки соблюдения стандартов."
    ),
    "Хочу записаться на консультацию завтра.": (
        "другое",
        "Здравствуйте! Для записи на консультацию выберите удобный слот в онлайн-расписании на портале либо укажите желаемое время в ответном сообщении."
    ),
    "Пропал Wi-Fi в корпусе В.": (
        "жалоба",
        "Здравствуйте! Обращение зарегистрировано. IT-служба уже проводит диагностику оборудования сети в корпусе В."
    ),
    "Где парковка для гостей?": (
        "справка",
        "Здравствуйте! Гостевая парковка расположена с северной стороны главного здания (въезд со стороны КПП №1)."
    )
}

def classify_message(text: str):
    clean_text = text.strip()
    if clean_text in CUSTOM_REPLIES:
        return CUSTOM_REPLIES[clean_text]

    lower_text = clean_text.lower()
    for rule in RULES:
        if any(kw in lower_text for kw in rule["keywords"]):
            return rule["category"], rule["draft_template"]

    return "другое", "Здравствуйте! Ваше обращение получено и передано специалисту."

def main():
    file_path = Path(__file__).parent / "messages.txt"
    if not file_path.exists():
        print(f"Ошибка: файл {file_path} не найден.")
        sys.exit(1)

    with open(file_path, "r", encoding="utf-8") as f:
        messages = [line.strip() for line in f if line.strip()]

    print("=== РЕЗУЛЬТАТЫ КЛАССИФИКАЦИИ ОБРАЩЕНИЙ ===\n")
    for idx, msg in enumerate(messages, 1):
        category, reply = classify_message(msg)
        print(f"[{idx}] Обращение: {msg}")
        print(f"    Категория: {category}")
        print(f"    Черновик ответа: {reply}\n")

if __name__ == "__main__":
    main()
